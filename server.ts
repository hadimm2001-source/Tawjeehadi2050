// Lazy-initialize Gemini client
let aiClient: GoogleGenAI | null = null;
let apiKeyInvalid = false;
let apiKeyChecked = false;
let isCheckingKey = false;

function getAi(): GoogleGenAI | null {
  if (apiKeyInvalid) {
    return null;
  }
  if (!aiClient) {
    const apiKey = process.env.GEMINI_API_KEY;
    if (apiKey && apiKey !== "MY_GEMINI_API_KEY") {
      try {
        aiClient = new GoogleGenAI({
          apiKey: apiKey,
          httpOptions: {
            headers: {
              'User-Agent': 'aistudio-build',
            }
          }
        });
      } catch (e) {
        console.error("Failed to initialize Gemini client:", e);
      }
    }
  }
  return aiClient;
}

// Check if AI is active
app.get("/api/ai-status", async (req, res) => {
  const ai = getAi();
  if (ai && !apiKeyChecked && !isCheckingKey) {
    isCheckingKey = true;
    try {
      // Do a quick test call with a low timeout or small generation
      await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: "test",
      });
      apiKeyChecked = true;
    } catch (error: any) {
      const errStr = String(error?.message || error);
      if (errStr.includes("leaked") || errStr.includes("API key") || errStr.includes("403") || errStr.includes("PERMISSION_DENIED")) {
        apiKeyInvalid = true;
        aiClient = null;
        console.warn("Detected invalid or leaked API key on startup. Automatically switched to Offline Mode.");
      }
      apiKeyChecked = true;
    } finally {
      isCheckingKey = false;
    }
  }
  res.json({ active: !!getAi() });
});

