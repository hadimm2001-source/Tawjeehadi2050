// 1. المستشار الإداري الذكي
app.post("/api/chat", async (req, res) => {
  const { message, history } = req.body;
  if (!message) {
    return res.status(400).json({ error: "الرسالة مطلوبة" });
  }

  const ai = getAi();
  if (!ai) {
    // Elegant offline fallback
    const offlineText = generateOfflineChatResponse(message);
    return res.json({ 
      text: offlineText + "\n\n> 💡 *تنبيه إرشادي*: تم تفعيل وضع المستشار الذكي المحلي (Offline AI) لضمان استمرارية الخدمة. يرجى تزويد التطبيق بمفتاح Gemini API صالح في الإعدادات للاستفادة الكاملة من القدرات التوليدية المفتوحة."
    });
  }

  try {
    const systemInstruction = `أنت مستشار إداري خبير وموجه طلابي محترف في مدارس المملكة العربية السعودية لعام 1447هـ.
تجيب على استفسارات الموجهين والمعلمين وأولياء الأمور بدقة بالغة وبأسلوب تربوي رصين، معتمداً على اللوائح الرسمية لوزارة التعليم (مثل لائحة السلوك والمواظبة وقواعد الانضباط المدرسي).
إذا سئلت عن الغياب، أو التأخر، أو الدرجات، أو السلوك، أو التنمر، أو الخطط العلاجية، أعط إجابات قانونية وتربوية واضحة مفرزة بنقاط وبطريقة منظمة وجذابة باستخدام Markdown.`;

    const chatHistory = history ? history.map((h: any) => ({
      role: h.role,
      parts: [{ text: h.content }]
    })) : [];

    const chat = ai.chats.create({
      model: "gemini-3.5-flash",
      config: {
        systemInstruction,
        temperature: 0.7,
      },
      history: chatHistory,
    });

    const response = await chat.sendMessage({ message });
    res.json({ text: response.text });
  } catch (error: any) {
    const errStr = String(error?.message || error);
    const isApiKeyError = errStr.includes("leaked") || errStr.includes("API key") || errStr.includes("403") || errStr.includes("PERMISSION_DENIED");
    if (isApiKeyError) {
      apiKeyInvalid = true;
      aiClient = null;
      console.warn("Gemini API Key is invalid or leaked. Switched to offline advisor.");
    } else {
      console.error("Gemini API Error, using offline advisor fallback:", error);
    }
    const offlineText = generateOfflineChatResponse(message);
    res.json({ 
      text: offlineText + "\n\n> 💡 *تنبيه إرشادي*: تم تفعيل وضع المستشار الذكي المحلي (Offline AI) لضمان استمرارية الخدمة. يرجى تزويد التطبيق بمفتاح Gemini API صالح في الإعدادات للاستفادة الكاملة من القدرات التوليدية المفتوحة."
    });
  }
});

